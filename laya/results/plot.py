"""Summary table and figures from results/runs.csv (one row per run).

Writes results/summary.md and results/figures/*.png.

  python results/plot.py      # needs matplotlib
"""
import csv
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
FIG = RES / "figures"
REFERENCE = "GCP T4 x2"  # the official 2-GPU setup
FREE = {"Kaggle", "Colab"}

NUMERIC = ["seed", "epoch1_s", "epoch2_s", "epoch3_s", "epoch4_s", "mean_epoch_2_4_s", "train_s",
           "peak_memory_gb", "accuracy", "brier", "ece", "eval_s", "list_price_usd_per_h",
           "train_cost_usd", "usd_per_1m_seq"]


def load():
    with open(RES / "runs.csv", newline="") as f:
        runs = list(csv.DictReader(f))
    for r in runs:
        for k in NUMERIC:
            r[k] = float(r[k])
    return runs


def by_config(runs):
    out = {}
    for r in runs:
        out.setdefault(r["config"], []).append(r)
    return out


def mean_sd(xs, nd):
    if len(xs) == 1:
        return f"{xs[0]:.{nd}f}"
    return f"{statistics.mean(xs):.{nd}f} ± {statistics.stdev(xs):.{nd}f}"


def summary(groups):
    ref = statistics.mean(r["mean_epoch_2_4_s"] for r in groups[REFERENCE])
    out = ["# Results", "",
           "Generated by [`plot.py`](plot.py) from [`runs.csv`](runs.csv). Mean ± sample std over seeds "
           "42, 43, 44. TPU rows evaluate with fixed shapes, GPU rows with the official loop. Costs are "
           "GCP on-demand list prices; Kaggle and Colab runs are free, and their costs, in parentheses, are "
           "what the same hardware costs on GCP.", "",
           "| Configuration | Mean epoch, 2-4 (s) | Speed-up | Train, 4 epochs (s) | Peak memory (GB) | Accuracy | "
           "Brier | ECE | Eval, 400 cases (s) | Training cost (USD) | USD per 1M seq |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for c, rs in groups.items():
        col = lambda k, nd: mean_sd([r[k] for r in rs], nd)  # noqa: E731
        paren = (lambda s: f"({s})") if rs[0]["platform"] in FREE else (lambda s: s)
        speed = ref / statistics.mean(r["mean_epoch_2_4_s"] for r in rs)
        out.append(f"| {c} | {col('mean_epoch_2_4_s', 1)} | {speed:.2f}x | {col('train_s', 0)} | "
                   f"{col('peak_memory_gb', 2)} | {col('accuracy', 3)} | {col('brier', 3)} | {col('ece', 3)} | "
                   f"{col('eval_s', 0)} | {paren(col('train_cost_usd', 2))} | {paren(col('usd_per_1m_seq', 1))} |")
    out += ["", "![Mean epoch time](figures/epoch_time.png)", "", "![Time vs cost](figures/time_vs_cost.png)", "",
            "![Accuracy per seed](figures/accuracy.png)", "", "![Per-epoch time](figures/epochs.png)", ""]
    return "\n".join(out)


def color(c):
    return "#4c72b0" if "T4" in c else "#dd8452"


def finish(fig, ax, name):
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG / name, dpi=150)
    plt.close(fig)


def figures(groups):
    FIG.mkdir(parents=True, exist_ok=True)
    names = list(groups)

    fig, ax = plt.subplots(figsize=(8, 3.6))
    means = [statistics.mean(r["mean_epoch_2_4_s"] for r in groups[c]) for c in names]
    sds = [statistics.stdev(r["mean_epoch_2_4_s"] for r in groups[c]) for c in names]
    bars = ax.bar(names, means, yerr=sds, capsize=3, color=[color(c) for c in names])
    for b, m, sd in zip(bars, means, sds):
        ax.annotate(f"{m:.0f}", (b.get_x() + b.get_width() / 2, m + sd), xytext=(0, 2), textcoords="offset points",
                    ha="center", va="bottom", fontsize=8)
    ax.set_ylabel("seconds")
    ax.set_title("Mean epoch time, epochs 2-4 (lower is better)")
    ax.tick_params(axis="x", labelrotation=20, labelsize=8)
    finish(fig, ax, "epoch_time.png")

    fig, ax = plt.subplots(figsize=(7, 4.2))
    for c in names:
        rs = groups[c]
        free = rs[0]["platform"] in FREE
        ax.scatter(statistics.mean(r["train_s"] / 60 for r in rs), statistics.mean(r["train_cost_usd"] for r in rs),
                   s=60 if free else 32, marker="s" if free else "o", zorder=3 if free else 4, label=c + (" (free; GCP-equivalent)" if free else ""))
    # Baseline: the official setup. Points below and to the left are faster and cheaper.
    ref = groups[REFERENCE]
    rt, rc = statistics.mean(r["train_s"] / 60 for r in ref), statistics.mean(r["train_cost_usd"] for r in ref)
    ax.axvline(rt, color="0.6", linestyle="--", linewidth=1, zorder=0)
    ax.axhline(rc, color="0.6", linestyle="--", linewidth=1, zorder=0)
    ax.annotate("official setup (GCP T4 x2)", (rt, rc), xytext=(6, 6), textcoords="offset points",
                fontsize=8, color="0.4")
    ax.text(1, 0.02, "faster and cheaper\nthan the official setup", fontsize=8, color="0.4", va="bottom")
    ax.set_xlabel("training time, 4 epochs (min)")
    ax.set_ylabel("training cost at GCP list price (USD)")
    ax.set_title("Time vs cost to train (mean of 3 seeds)")
    ax.set_xlim(left=0)
    ax.set_ylim(0, rc * 1.2)
    ax.legend(fontsize=8, frameon=False, loc="lower right")
    finish(fig, ax, "time_vs_cost.png")

    fig, ax = plt.subplots(figsize=(8, 3.6))
    for i, c in enumerate(names):
        accs = [r["accuracy"] for r in groups[c]]
        ax.scatter([i] * len(accs), accs, color=color(c), s=40)
        ax.hlines(statistics.mean(accs), i - 0.25, i + 0.25, color=color(c))
    ax.set_xticks(range(len(names)), names, rotation=20, fontsize=8)
    ax.set_ylabel("test accuracy")
    ax.set_title("Test accuracy per seed (line: mean)")
    finish(fig, ax, "accuracy.png")

    fig, ax = plt.subplots(figsize=(8, 3.6))
    for c in names:
        rs = groups[c]
        ep = [statistics.mean(r[f"epoch{i}_s"] for r in rs) for i in range(1, 5)]
        ax.plot(range(1, 5), ep, marker="o", linestyle="-" if "T4" in c else "--", label=c)
    ax.set_xlabel("epoch")
    ax.set_ylabel("seconds (mean over seeds)")
    ax.set_xticks(range(1, 5))
    ax.set_title("Per-epoch training time (epoch 1 includes TPU compilation)")
    ax.legend(fontsize=7)
    finish(fig, ax, "epochs.png")


def main():
    groups = by_config(load())
    figures(groups)
    (RES / "summary.md").write_text(summary(groups))
    print("wrote results/summary.md and results/figures/")


if __name__ == "__main__":
    main()
